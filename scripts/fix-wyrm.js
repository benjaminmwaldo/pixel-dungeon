function render(frame, name) {
  const rows = frame.map((groups, i) => {
    const line = groups.join('');
    if (line.length !== 32) throw new Error(`${name} row ${i} is ${line.length}px`);
    return line;
  });
  if (rows.length !== 32) throw new Error(`${name} has ${rows.length} rows`);
  return `export const ${name} = \`\n${rows.join('\n')}\`;`;
}

const path = new URL('../client/art/sprites.js', import.meta.url);
let src = readFileSync(path, 'utf8');

for (const [name, frame] of [['WYRM1', F1], ['WYRM2', F2]]) {
  const re = new RegExp(`export const ${name} = \`[\\s\\S]*?\`;`);
  if (!re.test(src)) throw new Error(`could not find ${name} in sprites.js`);
  src = src.replace(re, render(frame, name));
}

writeFileSync(path, src);
