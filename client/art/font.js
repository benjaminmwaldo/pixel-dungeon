// Validate at load — a bad glyph should shout, not silently render garbage.
for (const [ch, def] of Object.entries(GLYPHS)) {
  const rows = def.split('/');
  if (rows.length !== 8) throw new Error(`font "${ch}": ${rows.length} rows, expected 8`);
  for (const r of rows) {
    if (r.length !== 8) throw new Error(`font "${ch}": row "${r}" is ${r.length}px, expected 8`);
  }
}
